  // Função que executa a transição animada de texto e traduz a página (GSAP Decode / Scramble)
  function changeLanguage(langCode, flagSrc, isInitialLoad = false) {
    const elements = document.querySelectorAll('[data-i18n]');
    const hasTranslation = translations[langCode] && Object.keys(translations[langCode]).length > 0;
    const langToUse = hasTranslation ? langCode : 'pt-br';

    const finalFlag = flagSrc || flagMap[langToUse] || '/img/flags/pt-br.jpg';
    if (currentFlagImg) {
      currentFlagImg.src = finalFlag;
    }

    try {
      localStorage.setItem('userLang', langToUse);
    } catch (_) {}

    // Entrega o currículo em inglês para qualquer idioma que não seja o português
    const cvBtn = document.getElementById('btn-download-cv') || document.querySelector('a[href*="_CV_"]');
    if (cvBtn) {
      const isPortuguese = langToUse.startsWith('pt');
      if (isPortuguese) {
        cvBtn.href = '/pdf/Lucas_Apolinario_CV_Dev.pdf';
        cvBtn.setAttribute('download', 'Lucas_Apolinario_CV_Dev.pdf');
      } else {
        cvBtn.href = '/pdf/Lucas_Apolinario_CV_En.pdf';
        cvBtn.setAttribute('download', 'Lucas_Apolinario_CV_En.pdf');
      }
    }

    // Efeito Scramble / Hacker Text Decode
    const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz!@#$%^&*()';

    elements.forEach((el, index) => {
      const key = el.getAttribute('data-i18n');
      const finalStr = translations[langToUse] && translations[langToUse][key] ? translations[langToUse][key] : '';

      if (!finalStr) return;

      if (el._langTween) el._langTween.kill();

      // Carregamento inicial: aplica direto sem animação
      if (isInitialLoad) {
        if (finalStr.includes('<')) {
          el.innerHTML = finalStr;
        } else {
          el.textContent = finalStr;
        }
        gsap.set(el, { opacity: 1, y: 0 });
      } else {
        // Troca de idioma interativa: decodificação hacker animada
        if (finalStr.includes('<')) {
          el._langTween = gsap.to(el, {
            opacity: 0,
            duration: 0.15,
            onComplete: () => {
              el.innerHTML = finalStr;
              gsap.to(el, { opacity: 1, duration: 0.3 });
            }
          });
        } else {
          gsap.set(el, { opacity: 1 });
          const obj = { step: 0 };
          const delay = Math.min(index * 0.02, 0.4);

          el._langTween = gsap.to(obj, {
            step: finalStr.length,
            duration: 0.5,
            delay: delay,
            ease: 'power2.inOut',
            onUpdate: () => {
              const currentStep = Math.floor(obj.step);
              let result = '';
              for (let i = 0; i < finalStr.length; i++) {
                if (i < currentStep) {
                  result += finalStr[i];
                } else if (finalStr[i] === ' ') {
                  result += ' ';
                } else {
                  result += letters[Math.floor(Math.random() * letters.length)];
                }
              }
              el.textContent = result;
            },
            onComplete: () => {
              el.textContent = finalStr;
            }
          });
        }
      }
    });

    // Atualiza todos os triggers do GSAP com as novas alturas dos textos
    setTimeout(() => {
      ScrollTrigger.refresh();
    }, isInitialLoad ? 80 : 650);
  }

  const langSwitcher = document.querySelector('.lang-switcher');
  let closeTimer = null;

  function openDropdown() {
    if (closeTimer) {
      clearTimeout(closeTimer);
      closeTimer = null;
    }
    langDropdown.classList.add('show');
    langBtn.classList.add('active');
  }

  function closeDropdown(delay = 350) {
    if (closeTimer) clearTimeout(closeTimer);
    if (delay === 0) {
      langDropdown.classList.remove('show');
      langBtn.classList.remove('active');
    } else {
      closeTimer = setTimeout(() => {
        langDropdown.classList.remove('show');
        langBtn.classList.remove('active');
      }, delay);
    }
  }

  if (langSwitcher) {
    langSwitcher.addEventListener('mouseenter', openDropdown);
    langSwitcher.addEventListener('mouseleave', () => closeDropdown(350));
  }

  // Eventos de clique nas opções de idioma
  langOptions.forEach((option) => {
    option.addEventListener('click', (e) => {
      const rawLang = e.currentTarget.getAttribute('data-i18n-lang') || e.currentTarget.getAttribute('data-i18n') || '';
      const langCode = rawLang.replace('lang-', '').toLowerCase();
      const imgEl = e.currentTarget.querySelector('img');
      const flagSrc = imgEl ? imgEl.src : flagMap[langCode];

      changeLanguage(langCode, flagSrc, false);
      closeDropdown(0);
    });
  });

  // Toggle dropdown via clique (para dispositivos touch / mobile)
  langBtn.addEventListener('click', (e) => {
    e.stopPropagation();
    if (closeTimer) clearTimeout(closeTimer);
    const isShowing = langDropdown.classList.toggle('show');
    langBtn.classList.toggle('active', isShowing);
  });

  document.addEventListener('click', (e) => {
    if (!langDropdown.contains(e.target) && e.target !== langBtn) {
      closeDropdown(0);
    }
  });

  // Detecção automática de idioma
  function detectUserLanguage() {
    let savedLang = null;
    try {
      savedLang = localStorage.getItem('userLang');
    } catch (_) {}

    if (savedLang && translations[savedLang]) {
      const flag = flagMap[savedLang] || '/img/flags/pt-br.jpg';
      changeLanguage(savedLang, flag, true);
      return;
    }

    const browserLang = (navigator.language || 'pt-BR').toLowerCase();
    const supportedLangs = Object.keys(translations);

    let initialLang = 'pt-br';
    if (supportedLangs.includes(browserLang)) {
      initialLang = browserLang;
    } else {
      const short = browserLang.split('-')[0];
      if (short === 'pt') initialLang = 'pt-br';
      else if (short === 'es') initialLang = 'es-es';
      else if (short === 'zh') initialLang = 'zh-cn';
      else if (supportedLangs.includes(short)) initialLang = short;
    }

    const flag = flagMap[initialLang] || '/img/flags/pt-br.jpg';
    changeLanguage(initialLang, flag, true);
  }

  detectUserLanguage();
